constexpr uint8_t kHeaderIconSize = 24;
constexpr size_t kHeaderIconBytes =
    (kHeaderIconSize * kHeaderIconSize) / 2;
using HeaderIconBitmap = std::array<uint8_t, kHeaderIconBytes>;
constexpr uint8_t kToolbarLightWidth = 10;
constexpr uint8_t kToolbarLightHeight = 18;
using ToolbarLightBitmap =
    std::array<uint8_t,
               ((kToolbarLightWidth + 1) / 2) * kToolbarLightHeight>;

uint8_t alphaAt(const uint8_t* bitmap, uint8_t width, uint8_t x,
                uint8_t y) {
  const size_t stride = (width + 1) / 2;
  const uint8_t packed = bitmap[y * stride + x / 2];
  return (x & 1) ? packed & 0x0F : packed >> 4;
}

void setAlpha(HeaderIconBitmap& bitmap, uint8_t x, uint8_t y,
              uint8_t alpha) {
  uint8_t& packed = bitmap[y * (kHeaderIconSize / 2) + x / 2];
  if (x & 1) packed = static_cast<uint8_t>((packed & 0xF0) | alpha);
  else packed = static_cast<uint8_t>((packed & 0x0F) | (alpha << 4));
}

HeaderIconBitmap fitHeaderIcon(const uint8_t* source, uint8_t sourceWidth,
                               uint8_t sourceHeight) {
  HeaderIconBitmap result{};
  uint8_t width = kHeaderIconSize;
  uint8_t height = kHeaderIconSize;
  if (sourceWidth > sourceHeight) {
    height = static_cast<uint8_t>((sourceHeight * kHeaderIconSize +
                                   sourceWidth / 2) / sourceWidth);
  } else if (sourceHeight > sourceWidth) {
    width = static_cast<uint8_t>((sourceWidth * kHeaderIconSize +
                                  sourceHeight / 2) / sourceHeight);
  }
  const uint8_t offsetX = (kHeaderIconSize - width) / 2;
  const uint8_t offsetY = (kHeaderIconSize - height) / 2;
  for (uint8_t y = 0; y < height; ++y) {
    const uint8_t sourceY = static_cast<uint8_t>(y * sourceHeight / height);
    for (uint8_t x = 0; x < width; ++x) {
      const uint8_t sourceX = static_cast<uint8_t>(x * sourceWidth / width);
      setAlpha(result, offsetX + x, offsetY + y,
               alphaAt(source, sourceWidth, sourceX, sourceY));
    }
  }
  return result;
}

ToolbarLightBitmap fitToolbarLightbulb() {
  ToolbarLightBitmap result{};
  constexpr size_t stride = (kToolbarLightWidth + 1) / 2;
  for (uint8_t y = 0; y < kToolbarLightHeight; ++y) {
    const uint8_t sourceY = static_cast<uint8_t>(y * 24 /
                                                 kToolbarLightHeight);
    for (uint8_t x = 0; x < kToolbarLightWidth; ++x) {
      const uint8_t sourceX = static_cast<uint8_t>(x * 14 /
                                                   kToolbarLightWidth);
      const uint8_t alpha = alphaAt(kLightbulbBitmap, 14, sourceX, sourceY);
      uint8_t& packed = result[y * stride + x / 2];
      if (x & 1) packed = static_cast<uint8_t>((packed & 0xF0) | alpha);
      else packed = static_cast<uint8_t>((packed & 0x0F) | (alpha << 4));
    }
  }
  return result;
}

