bool getGlyphDsc14(const lv_font_t*, lv_font_glyph_dsc_t* dsc,
                   uint32_t letter, uint32_t) {
  if (letter != kLightbulbCodepoint) return false;
  dsc->adv_w = 14;
  dsc->box_w = kToolbarLightWidth;
  dsc->box_h = kToolbarLightHeight;
  dsc->ofs_x = 2;
  dsc->ofs_y = 0;
  dsc->stride = (kToolbarLightWidth + 1) / 2;
  dsc->format = LV_FONT_GLYPH_FORMAT_A4;
  dsc->gid.index = 1;
  dsc->is_placeholder = false;
  return true;
}

bool getGlyphDsc28(const lv_font_t*, lv_font_glyph_dsc_t* dsc,
                   uint32_t letter, uint32_t) {
  if (letter == kLightbulbCodepoint) {
    dsc->adv_w = 16;
    dsc->box_w = 14;
    dsc->box_h = 24;
    dsc->ofs_x = 1;
    dsc->ofs_y = 0;
  } else if (letter == kPowerCordCodepoint) {
    dsc->adv_w = 26;
    dsc->box_w = 24;
    dsc->box_h = 17;
    dsc->ofs_x = 1;
    dsc->ofs_y = 4;
  } else if (letter == kFanCodepoint || letter == kSpigotCodepoint || letter == kFlamesCodepoint) {
    dsc->adv_w = 26; dsc->box_w = 24; dsc->box_h = 24;
    dsc->ofs_x = 1; dsc->ofs_y = 0;
  } else {
    return false;
  }
  dsc->stride = (dsc->box_w + 1) / 2;
  dsc->format = LV_FONT_GLYPH_FORMAT_A4;
  dsc->gid.index = letter == kLightbulbCodepoint ? 1 : letter == kPowerCordCodepoint ? 2
                   : letter == kFanCodepoint ? 3 : letter == kSpigotCodepoint ? 4 : 5;
  dsc->is_placeholder = false;
  return true;
}

const void* renderA4Glyph(const uint8_t* source, lv_font_glyph_dsc_t* dsc,
                          lv_draw_buf_t* drawBuffer) {
  if (source == nullptr) return nullptr;
  if (dsc->req_raw_bitmap) return source;
  if (drawBuffer == nullptr) return nullptr;
  for (uint16_t y = 0; y < dsc->box_h; ++y) {
    uint8_t* output = drawBuffer->data + y * drawBuffer->header.stride;
    const uint8_t* input = source + y * dsc->stride;
    for (uint16_t x = 0; x < dsc->box_w; ++x) {
      const uint8_t packed = input[x / 2];
      const uint8_t alpha = (x & 1U) ? (packed & 0x0F) : (packed >> 4);
      output[x] = static_cast<uint8_t>(alpha * 17U);
    }
  }
  lv_draw_buf_flush_cache(drawBuffer, nullptr);
  return drawBuffer;
}

const void* getGlyphBitmap14(lv_font_glyph_dsc_t* dsc,
                             lv_draw_buf_t* drawBuffer) {
  return renderA4Glyph(
      dsc->gid.index == 1 ? kToolbarLightbulbBitmap.data() : nullptr,
      dsc, drawBuffer);
}

const void* getGlyphBitmap28(lv_font_glyph_dsc_t* dsc,
                             lv_draw_buf_t* drawBuffer) {
  const uint8_t* source = dsc->gid.index == 1 ? kLightbulbBitmap
                           : dsc->gid.index == 5 ? kFlamesBitmap
                           : dsc->gid.index == 4 ? kSpigotBitmap
                           : dsc->gid.index == 3 ? kFanBitmap
                           : dsc->gid.index == 2 ? kPowerCordBitmap
                                                 : nullptr;
  return renderA4Glyph(source, dsc, drawBuffer);
}

